function plot_regions(domainLength, material_boundaries, ...
                      eps_r_list, mu_r_list, sigma_e_list, sigma_m_list, ...
                      left_boundary, right_boundary)
    figure; hold on;
    colors = lines(numel(eps_r_list));

    for i = 1:numel(eps_r_list)
        x_start = material_boundaries(i,1);
        x_end   = material_boundaries(i,2);

        rectangle('Position', [x_start, 0, x_end - x_start, 1], ...
            'FaceColor', colors(i,:), 'FaceAlpha', 0.35, ...
            'EdgeColor', 'k', 'LineWidth', 1.2);

        text((x_start + x_end)/2, 0.5, ...
            sprintf(['Material %d\n' ...
                     '\\epsilon_r = %.1f\n' ...
                     '\\mu_r = %.1f\n' ...
                     '\\sigma_e = %.1f \n' ...
                     '\\sigma_m = %.1f'], ...
                     i, eps_r_list(i), mu_r_list(i), ...
                     sigma_e_list(i), sigma_m_list(i)), ...
            'HorizontalAlignment', 'center', ...
            'VerticalAlignment', 'middle', 'FontSize', 9);
    end

    xline(0, 'k-', 'LineWidth', 2);
    xline(domainLength, 'k-', 'LineWidth', 2);

    label_boundary(0.02*domainLength,  boundary_string('Left',  left_boundary),  'left');
    label_boundary(0.98*domainLength,  boundary_string('Right', right_boundary), 'right');

    xlim([0 domainLength]); ylim([0 1]); yticks([]);
    xlabel('Position (m)');
    title('One-Dimensional Multilayer Electromagnetic Structure with Boundaries');
    grid on; box on;
end

function s = boundary_string(side, bc)
    if strcmpi(bc, 'c')
        s = sprintf('%s: PEC (Closed)', side);
    else
        s = sprintf('%s: Open', side);
    end
end

function label_boundary(xpos, str, align)
    text(xpos, 0.92, str, ...
        'HorizontalAlignment', align, 'VerticalAlignment', 'top', ...
        'BackgroundColor', 'white', 'EdgeColor', 'k', ...
        'FontSize', 9, 'FontWeight', 'bold');
end