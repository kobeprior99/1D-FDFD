function [Gamma, T] = sweep_frequencies(frequencies, x, eps_r, mu_r, ...
                                        sigma_e, sigma_m, eps0, mu0, ...
                                        left_boundary, right_boundary)
    Gamma = zeros(size(frequencies));
    T     = zeros(size(frequencies));

    for k = 1:numel(frequencies)
        [Gamma(k), T(k)] = FDFD(frequencies(k), x, eps_r, mu_r, ...
                                sigma_e, sigma_m, eps0, mu0, ...
                                left_boundary, right_boundary);
    end
end